export async function bootstrapPublicCache() {
  try {
    const count = await db.publicMovies.count();
    // If fewer than 25 movies, wipe and seed with our comprehensive collection
    if (count < 25) {
      await db.publicMovies.clear();
      await db.publicMovies.bulkPut(
        SAMPLE_COMMUNITY_MOVIES.map((movie) => ({
          key: movie.key,
          movie,
          expiresAt: Date.now() + 365 * 86400000,
        })),
      );
    }
  } catch (_e) {
    void _e;
  }
}
