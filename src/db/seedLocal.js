export async function bootstrapPublicCache() {
  try {
    const count = await db.publicMovies.count();
    // Always refresh or populate if empty or missing posters
    if (count === 0) {
      await db.publicMovies.bulkPut(
        SAMPLE_COMMUNITY_MOVIES.map((movie) => ({
          key: movie.key,
          movie,
          expiresAt: Date.now() + 365 * 86400000,
        })),
      );
    } else {
      // Update any existing seeded movie if it has null posterUrl
      const existing = await db.publicMovies.get(SAMPLE_COMMUNITY_MOVIES[0].key);
      if (existing && !existing.movie?.posterUrl) {
        await db.publicMovies.bulkPut(
          SAMPLE_COMMUNITY_MOVIES.map((movie) => ({
            key: movie.key,
            movie,
            expiresAt: Date.now() + 365 * 86400000,
          })),
        );
      }
    }
  } catch (_e) {
    void _e;
  }
}
